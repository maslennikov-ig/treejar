export type TranslateFn = (key: TranslationKey, vars?: TranslateVars) => string;

function interpolate(template: string, vars?: TranslateVars): string {
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

export function translate(lang: Lang, key: TranslationKey, vars?: TranslateVars): string {
    return interpolate(DICTIONARIES[lang][key] ?? DICTIONARIES.ru[key] ?? key, vars);
}

function localeOf(lang: Lang): string {
    return lang === 'ru' ? 'ru-RU' : 'en-US';
}

export interface I18nValue {
    lang: Lang;
    setLang: (lang: Lang) => void;
    t: TranslateFn;
    /** Dynamic key lookup with a fallback (for server-provided codes). */
    tx: (key: string, fallback: string, vars?: TranslateVars) => string;
    /** Localized label for a status/enum value; falls back to the raw value. */
    label: (value: string | null | undefined) => string;
    formatDate: (value: string) => string;
    formatDateTime: (value: string) => string;
    formatNumber: (value: number, fractionDigits?: number) => string;
    formatCurrency: (amount: number | null | undefined, currency?: string) => string;
    formatDuration: (seconds: number | null) => string;
}

export function createI18nValue(lang: Lang, setLang: (lang: Lang) => void = () => undefined): I18nValue {
    const dictionary = DICTIONARIES[lang] as Record<string, string>;
    const locale = localeOf(lang);
    const t: TranslateFn = (key, vars) => translate(lang, key, vars);
    const tx = (key: string, fallback: string, vars?: TranslateVars) =>
        interpolate(key in dictionary ? dictionary[key] : fallback, vars);
    return {
        lang,
        setLang,
        t,
        tx,
        label: (value) => {
            if (!value) return '—';
            const key = `status.${value}`;
            return key in dictionary ? dictionary[key] : value.replace(/_/g, ' ');
        },
        formatDate: (value) =>
            new Intl.DateTimeFormat(locale, {
                day: '2-digit',
                month: '2-digit',
                hour: '2-digit',
                minute: '2-digit',
            }).format(new Date(value)),
        formatDateTime: (value) =>
            new Intl.DateTimeFormat(locale, {
                dateStyle: 'medium',
                timeStyle: 'short',
            }).format(new Date(value)),
        formatNumber: (value, fractionDigits) => {
            const safe = Number.isFinite(value) ? value : 0;
            return new Intl.NumberFormat(locale, fractionDigits === undefined
                ? { maximumFractionDigits: 2 }
                : { minimumFractionDigits: fractionDigits, maximumFractionDigits: fractionDigits }).format(safe);
        },
        formatCurrency: (amount, currency = 'AED') => {
            if (amount === null || amount === undefined || !Number.isFinite(amount)) return '—';
            const formatted = new Intl.NumberFormat(locale, { maximumFractionDigits: 0 }).format(amount);
            return `${formatted} ${currency}`;
        },
        formatDuration: (seconds) => {
            if (seconds === null || seconds === undefined) return '—';
            if (seconds < 60) return lang === 'ru' ? `${Math.round(seconds)} с` : `${Math.round(seconds)}s`;
            const minutes = new Intl.NumberFormat(locale, { minimumFractionDigits: 1, maximumFractionDigits: 1 }).format(seconds / 60);
            return lang === 'ru' ? `${minutes} мин` : `${minutes} min`;
        },
    };
}

export function readStoredLang(): Lang | null {
    try {
        if (typeof window === 'undefined' || !window.localStorage) return null;
        const stored = window.localStorage.getItem(LANG_STORAGE_KEY);
        return stored === 'ru' || stored === 'en' ? stored : null;
    } catch {
        return null;
    }
}

function storeLang(lang: Lang): void {
    try {
        if (typeof window === 'undefined' || !window.localStorage) return;
        window.localStorage.setItem(LANG_STORAGE_KEY, lang);
    } catch {
        // Storage may be blocked; the choice then lasts for this session only.
    }
    if (typeof document !== 'undefined') {
        document.documentElement.lang = lang;
    }
}

const I18nContext = createContext<I18nValue>(createI18nValue('ru'));

export function LanguageProvider({
    children,
    initialLang,
}: {
    children: ReactNode;
    initialLang?: Lang;
}) {
    const [lang, setLangState] = useState<Lang>(() => initialLang ?? readStoredLang() ?? 'ru');

    const setLang = useCallback((next: Lang) => {
        setLangState(next);
        storeLang(next);
    }, []);

    const value = useMemo(() => createI18nValue(lang, setLang), [lang, setLang]);

    return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
    return useContext(I18nContext);
}
